package cmd

import (
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"testing"
)

// Found in the owner's trial on 2026-09-21: `aether update` refused to run
// with "symbolic link is not an owned file: …/ts-host/node_modules/.bin/esbuild".
// The runtime itself installs the TS host's packages into the hub the first
// time a host-backed command falls back to the hub copy (prepareTsHostForExec),
// and npm always creates shortcut links under node_modules/.bin. The hub walk
// that plans an update refused any link it met, so one lazy install locked
// every later update out. Package folders are never synced (syncPathIgnored),
// so the walk must step over them -- while still refusing a link anywhere else.
func TestMaintenanceWalkSkipsInstalledPackagesButStillRefusesOtherLinks(t *testing.T) {
	root := t.TempDir()
	mustWrite := func(rel string) {
		t.Helper()
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte("x\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	mustWrite("docs/guide.md")
	mustWrite("ts-host/dist/host.js")
	mustWrite("ts-host/node_modules/esbuild/bin/esbuild")
	binDir := filepath.Join(root, "ts-host", "node_modules", ".bin")
	if err := os.MkdirAll(binDir, 0o755); err != nil {
		t.Fatal(err)
	}
	// The same relative link npm writes.
	if err := os.Symlink("../esbuild/bin/esbuild", filepath.Join(binDir, "esbuild")); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}

	files, err := listMaintenanceRegularFiles(root)
	if err != nil {
		t.Fatalf("installed packages in the hub locked the update walk out: %v", err)
	}
	want := []string{filepath.FromSlash("docs/guide.md"), filepath.FromSlash("ts-host/dist/host.js")}
	if !reflect.DeepEqual(files, want) {
		t.Fatalf("walk returned %v, want %v (package files must not be listed)", files, want)
	}

	// The refusal itself must survive: a link outside a package folder is
	// still not an owned file.
	if err := os.Symlink("guide.md", filepath.Join(root, "docs", "alias.md")); err != nil {
		t.Fatal(err)
	}
	if _, err := listMaintenanceRegularFiles(root); err == nil || !strings.Contains(err.Error(), "symbolic link") {
		t.Fatalf("a link outside node_modules was accepted: %v", err)
	}
}
